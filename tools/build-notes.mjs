#!/usr/bin/env node
/* Builds the notes section into plain static HTML so it works from GitHub Pages
   and from a double-clicked local file alike.

   Reads   notes/notes.json and notes/posts/<slug>.md (+ optional <slug>.en.md)
   Writes  notes/index.html, notes/<slug>.html, and the latest-notes block in index.html

   node tools/build-notes.mjs           build once
   node tools/build-notes.mjs --watch   rebuild whenever notes.json or a post changes */
import { existsSync, readFileSync, readdirSync, unlinkSync, watch, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const notesDir = join(root, "notes");
const postsDir = join(notesDir, "posts");
const homeFile = join(root, "index.html");
const { Marked } = createRequire(import.meta.url)(join(root, "assets/vendor/marked.min.js"));

const MARKER = "<!-- Generated by tools/build-notes.mjs. Edit notes/notes.json or notes/posts/*.md, then rebuild. -->";
const LATEST_COUNT = 3;
const RESERVED = new Set(["index"]);
const BODY_ZH = "\u0000ZH\u0000";
const BODY_EN = "\u0000EN\u0000";

/* ---------- Helpers ---------- */
const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);
const formatDate = (date) => date.replaceAll("-", ".");
const english = (note, field) => note[`${field}_en`] ?? note[field];
const indent = (text, spaces) => text.split("\n").map((line) => (line ? " ".repeat(spaces) + line : line)).join("\n");

function readingMinutes(text) {
  const han = (text.match(/\p{Script=Han}/gu) ?? []).length;
  const words = (text.replace(/\p{Script=Han}/gu, " ").match(/[A-Za-z0-9_]+/g) ?? []).length;
  return Math.max(1, Math.round(han / 400 + words / 220));
}

function slugify(text, used) {
  const base = text.trim().toLowerCase().replace(/[^\p{Letter}\p{Number}]+/gu, "-").replace(/^-|-$/g, "") || "section";
  let id = base;
  for (let n = 2; used.has(id); n += 1) id = `${base}-${n}`;
  used.add(id);
  return id;
}

function writeIfChanged(file, content) {
  if (existsSync(file) && readFileSync(file, "utf8") === content) return false;
  writeFileSync(file, content);
  return true;
}

/* ---------- Input ---------- */
function loadNotes() {
  let list;
  try {
    list = JSON.parse(readFileSync(join(notesDir, "notes.json"), "utf8"));
  } catch (error) {
    throw new Error(`notes/notes.json 无法解析：${error.message}`);
  }
  if (!Array.isArray(list)) throw new Error("notes/notes.json 的最外层应当是数组 [ … ]");

  const errors = [];
  const seen = new Set();
  list.forEach((note, index) => {
    const where = `notes.json 第 ${index + 1} 条${note?.slug ? `（${note.slug}）` : ""}`;
    if (typeof note !== "object" || note === null) return errors.push(`${where}：应当是一个对象 { … }`);
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(note.slug ?? "")) errors.push(`${where}：slug 只能用小写字母、数字和连字符`);
    else if (RESERVED.has(note.slug)) errors.push(`${where}：slug 不能叫 “${note.slug}”`);
    else if (seen.has(note.slug)) errors.push(`${where}：slug 与前面的文章重复`);
    seen.add(note.slug);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(note.date ?? "")) errors.push(`${where}：date 要写成 YYYY-MM-DD`);
    if (!note.title) errors.push(`${where}：缺少 title`);
    if (note.tags !== undefined && !(Array.isArray(note.tags) && note.tags.every((tag) => typeof tag === "string"))) errors.push(`${where}：tags 应当是字符串数组`);
    if (!note.hidden && note.slug && !existsSync(join(postsDir, `${note.slug}.md`))) errors.push(`${where}：找不到正文 notes/posts/${note.slug}.md`);
  });
  if (errors.length) throw new Error(errors.join("\n"));

  return list
    .filter((note) => !note.hidden)
    .sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
}

function renderMarkdown(markdown, used) {
  const toc = [];
  const parser = new Marked({ gfm: true });
  parser.use({
    renderer: {
      heading(text, level, raw) {
        const id = slugify(raw.replace(/[`*_~]/g, ""), used);
        if (level === 2) toc.push({ id, text: raw.replace(/[`*_~]/g, "") });
        return `<h${level} id="${id}">${text}</h${level}>\n`;
      }
    }
  });
  return { html: parser.parse(markdown).trim(), toc, minutes: readingMinutes(markdown) };
}

/* ---------- Shared markup ---------- */
const statusBadge = (note) => (note.draft ? `<span class="note-status" data-en="In progress">撰写中</span>` : "");

function noteRow(note, href, headingTag) {
  const tags = note.tags ?? [];
  const tagList = tags.length ? `<ul class="note-tags" role="list">${tags.map((tag) => `<li>${escapeHtml(tag)}</li>`).join("")}</ul>` : "";
  const summary = note.summary
    ? `\n    <p class="note-summary" data-en="${escapeHtml(english(note, "summary"))}">${escapeHtml(note.summary)}</p>`
    : "";
  return `<li class="note-row" data-tags="${escapeHtml(tags.join("|"))}">
  <a class="note-link" href="${href}">
    <time class="date" datetime="${note.date}">${formatDate(note.date)}</time>
    <div class="note-main">
      <${headingTag} class="note-title" data-en="${escapeHtml(english(note, "title"))}">${escapeHtml(note.title)}</${headingTag}>${summary ? indent(summary, 2) : ""}
    </div>
    <div class="note-side">${statusBadge(note)}${tagList}</div>
    <svg class="icon note-arrow" aria-hidden="true"><use href="#icon-right"/></svg>
  </a>
</li>`;
}

const emptyRow = `<li class="note-empty" data-en="The first note is on its way.">第一篇正在写，敬请期待。</li>`;

