/* ---------- Pages ---------- */
function indexPage(notes) {
  const tags = [...new Set(notes.flatMap((note) => note.tags ?? []))].sort((a, b) => a.localeCompare(b));
  const chips = tags.length
    ? `<div class="chips" id="notes-filters" role="group" aria-label="按标签筛选" data-en-label="Filter by tag" hidden>
  <button class="chip" type="button" data-en="All" aria-pressed="true">全部</button>
${tags.map((tag) => `  <button class="chip" type="button" data-tag="${escapeHtml(tag)}" aria-pressed="false">${escapeHtml(tag)}</button>`).join("\n")}
</div>\n`
    : "";
  const rows = notes.length ? notes.map((note) => noteRow(note, `${note.slug}.html`, "h2")).join("\n") : emptyRow;

  return page({
    title: "技术随笔 | Xianwei Guo",
    titleEn: "Notes | Xianwei Guo",
    description: "Xianwei Guo 的技术随笔：技术观察、工程实践与阅读思考。",
    pageName: "notes",
    main: `<section class="wrap notes-hero" aria-labelledby="notes-title">
  <p class="hero-status">
    <span class="pulse" aria-hidden="true"></span>
    <span>${notes.length} <span data-en="notes · updated as I go">篇 · 持续更新</span></span>
  </p>
  <h1 id="notes-title" lang="en">Field <em>notes</em><span class="dot">.</span></h1>
  <p class="notes-hero-lead" data-en="What I’ve been seeing and thinking about in tech: designs and papers I’ve read, lessons from projects I’ve built, and open questions worth writing down.">记录我在技术上的观察与思考：读过的设计和论文，做项目时的经验，以及一些还没想清楚、但值得写下来的问题。</p>
</section>

<section class="wrap notes-index" aria-label="全部随笔" data-en-label="All notes">
${indent(chips, 2)}  <ol class="note-list" id="notes-all" role="list">
${indent(rows, 4)}
  </ol>
</section>`
  });
}

function postPage(note, newer, older) {
  const used = new Set();
  const zh = renderMarkdown(readFileSync(join(postsDir, `${note.slug}.md`), "utf8"), used);
  const enFile = join(postsDir, `${note.slug}.en.md`);
  const en = existsSync(enFile) ? renderMarkdown(readFileSync(enFile, "utf8"), used) : null;

  const only = (language) => (en ? ` data-only="${language}"` : "");
  const toc = (rendered, language) => rendered.toc.length < 2 ? "" : `
<nav class="note-toc" aria-label="目录" data-en-label="Contents"${only(language)}>
  <p data-en="Contents">目录</p>
  <ol role="list">
${rendered.toc.map((item) => `    <li><a href="#${item.id}">${escapeHtml(item.text)}</a></li>`).join("\n")}
  </ol>
</nav>`;
  const tags = note.tags?.length
    ? `\n  <ul class="note-tags" role="list">${note.tags.map((tag) => `<li><a href="index.html?tag=${encodeURIComponent(tag)}">${escapeHtml(tag)}</a></li>`).join("")}</ul>`
    : "";
  const summary = note.summary
    ? `\n  <p class="note-lead" data-en="${escapeHtml(english(note, "summary"))}">${escapeHtml(note.summary)}</p>`
    : "";
  const pagerLink = (target, direction) => target ? `
  <a class="pager-link pager-${direction}" href="${target.slug}.html">
    <span class="pager-label" data-en="${direction === "older" ? "Previous" : "Next"}">${direction === "older" ? "上一篇" : "下一篇"}</span>
    <span class="pager-title" data-en="${escapeHtml(english(target, "title"))}">${escapeHtml(target.title)}</span>
  </a>` : "";
  const pager = older || newer
    ? `\n\n<nav class="note-pager" aria-label="更多随笔" data-en-label="More notes">${pagerLink(older, "older")}${pagerLink(newer, "newer")}\n</nav>`
    : "";

  const bodies = [
    en ? "" : `<p class="note-notice" lang="en">This note is currently only available in Chinese.</p>`,
    `<div class="prose" lang="zh-CN"${only("zh")}>\n${BODY_ZH}\n</div>`,
    en ? `<div class="prose" lang="en" data-only="en">\n${BODY_EN}\n</div>` : ""
  ].filter(Boolean).join("\n");

  // Rendered Markdown goes in after indenting the template: indentation inside <pre> would show.
  return page({
    title: `${note.title} | Xianwei Guo`,
    titleEn: `${english(note, "title")} | Xianwei Guo`,
    description: note.summary ?? note.title,
    pageName: "note",
    progress: true,
    main: `<article class="wrap note" aria-labelledby="note-title">
  <header class="note-head">
    <a class="text-link note-back" href="index.html"><svg class="icon" aria-hidden="true"><use href="#icon-left"/></svg><span data-en="All notes">全部随笔</span></a>
    <p class="note-meta">
      <time datetime="${note.date}">${formatDate(note.date)}</time>
      <span class="note-minutes" data-en="${(en ?? zh).minutes} min read">阅读约 ${zh.minutes} 分钟</span>${note.draft ? `\n      ${statusBadge(note)}` : ""}
    </p>
    <h1 id="note-title" data-en="${escapeHtml(english(note, "title"))}">${escapeHtml(note.title)}</h1>${indent(summary + tags, 2)}
  </header>

  <div class="note-layout">
    <div class="note-content">
${indent(bodies, 6)}
    </div>${indent(toc(zh, "zh") + (en ? toc(en, "en") : ""), 4)}
  </div>${indent(pager, 2)}
</article>`
  }).replace(/^[ \t]*\u0000ZH\u0000$/m, () => zh.html).replace(/^[ \t]*\u0000EN\u0000$/m, () => en?.html ?? "");
}

function updateHome(notes) {
  const home = readFileSync(homeFile, "utf8");
  const pattern = /([ \t]*)<!-- notes:latest:start[^>]*-->[\s\S]*?<!-- notes:latest:end -->/;
  const match = home.match(pattern);
  if (!match) throw new Error("index.html 里找不到 <!-- notes:latest:start --> 标记，无法更新主页的随笔列表");
  const space = match[1];
  const rows = notes.length
    ? notes.slice(0, LATEST_COUNT).map((note) => noteRow(note, `notes/${note.slug}.html`, "h3")).join("\n")
    : emptyRow;
  const block = `${space}<!-- notes:latest:start — generated by tools/build-notes.mjs -->\n${indent(rows, space.length)}\n${space}<!-- notes:latest:end -->`;
  return writeIfChanged(homeFile, home.replace(pattern, () => block));
}

/* ---------- Build ---------- */
function build() {
  const notes = loadNotes();
  const changed = [];
  const expected = new Set(["index.html", ...notes.map((note) => `${note.slug}.html`)]);

  if (writeIfChanged(join(notesDir, "index.html"), indexPage(notes))) changed.push("notes/index.html");
  notes.forEach((note, index) => {
    const file = join(notesDir, `${note.slug}.html`);
    if (writeIfChanged(file, postPage(note, notes[index - 1], notes[index + 1]))) changed.push(relative(root, file));
  });
  if (updateHome(notes)) changed.push("index.html");

  // Remove pages for notes that were deleted or hidden, but only files this script wrote.
  for (const name of readdirSync(notesDir)) {
    if (!name.endsWith(".html") || expected.has(name)) continue;
    const file = join(notesDir, name);
    if (readFileSync(file, "utf8").includes(MARKER)) {
      unlinkSync(file);
      changed.push(`${relative(root, file)}（已删除）`);
    }
  }

  const summary = changed.length ? `更新了 ${changed.length} 个文件：\n  ${changed.join("\n  ")}` : "没有变化";
  console.log(`✓ ${notes.length} 篇随笔。${summary}`);
}

function run() {
  try {
    build();
    return true;
  } catch (error) {
    console.error(`✗ 构建失败：\n${error.message}`);
    return false;
  }
}

if (process.argv.includes("--watch")) {
  run();
  let timer;
  const rebuild = () => { clearTimeout(timer); timer = setTimeout(run, 150); };
  watch(notesDir, (_, name) => name === "notes.json" && rebuild());
  watch(postsDir, (_, name) => name?.endsWith(".md") && rebuild());
  console.log("正在监听 notes/notes.json 和 notes/posts/，按 Ctrl+C 退出。");
} else if (!run()) {
  process.exitCode = 1;
}
